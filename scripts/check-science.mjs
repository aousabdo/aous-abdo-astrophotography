import fs from 'node:fs';
import assert from 'node:assert/strict';
import { photographs } from '../src/gallery.ts';
import * as p from '../src/physics.ts';
const insights=JSON.parse(fs.readFileSync(new URL('../src/science-insights.json',import.meta.url)));
const objects=JSON.parse(fs.readFileSync(new URL('../src/science-objects.json',import.meta.url)));
for(const photo of photographs) {
 assert.ok(objects[photo.id], `Missing science for ${photo.id}`);
 assert.ok(objects[photo.id].lead.length>80, `Incomplete summary for ${photo.id}`);
 assert.ok(insights[photo.id]?.explain.length>250, `Missing specific explanation for ${photo.id}`);
 assert.ok(insights[photo.id]?.reveal.length>50, `Missing insight for ${photo.id}`);
}
assert.equal(p.transmission(0),1);
assert.ok(Math.abs(p.transmission(1)-1/Math.E)<1e-12);
assert.ok(p.transmission(4)<p.transmission(1));
assert.ok(Math.abs(p.stromgrenRadiusPc(100)/p.stromgrenRadiusPc(1000)-10**(2/3))<1e-10);
assert.ok(p.stromgrenRadiusPc(10)>14&&p.stromgrenRadiusPc(10)<15);
assert.ok(Math.abs(p.expansionYears(1,20)/p.expansionYears(1,40)-2)<1e-12);
assert.equal(p.solarPeriodDays(0),25);
assert.equal(p.solarPeriodDays(90),36);
assert.equal(p.lunarFraction(0),1);
assert.equal(p.lunarFraction(90),.5);
assert.equal(p.lunarFraction(180),0);
assert.equal(p.shellPathLength(1,.75),0);
assert.ok(Math.abs(p.shellPathLength(0,.75)-.5)<1e-12);
assert.ok(p.shellPathLength(.75,.75)>p.shellPathLength(0,.75));
assert.equal(p.shellPathLength(-.4,.75),p.shellPathLength(.4,.75));
assert.ok(Math.abs(p.photonEnergyEv(656.3)-1.889)<.001);
assert.equal(p.hydrogenIonizes(60),true);
assert.equal(p.hydrogenIonizes(656.3),false);
assert.equal(p.hydrogenIonizes(500.7),false);
assert.ok(Math.abs(p.shadowLengthKm(1,45)-1)<1e-12);
assert.ok(p.shadowLengthKm(1,5)>p.shadowLengthKm(1,80));
assert.equal(p.planckContrast(5800),1);
assert.ok(p.planckContrast(4200)>0&&p.planckContrast(4200)<.2);
assert.ok(p.planckContrast(4500)>p.planckContrast(4000));
console.log(`All ${photographs.length} subjects have specific science insights. Model geometry, photon thresholds, shadows and brightness checks passed.`);
